"""Tag many requirements at once from the bulk bar. Run with scripts/ui-check-k8s.sh."""
import os
import sys

from playwright.sync_api import sync_playwright

BASE = os.environ.get("BASE_URL", "http://127.0.0.1:8000")
H = {"X-Requested-With": "fabulist"}
failures = []


def check(ok, what):
    print(("ok   " if ok else "FAIL ") + what)
    if not ok:
        failures.append(what)


with sync_playwright() as p:
    browser = p.chromium.launch()
    ctx = browser.new_context(viewport={"width": 1280, "height": 900}, bypass_csp=True)
    pid = ctx.request.post(BASE + "/api/projects", data={"name": "Tag UI", "platform": "generic"}, headers=H).json()["id"]
    for text in ("The system shall log every payment attempt.", "The system shall mask card numbers in reports."):
        ctx.request.post(f"{BASE}/api/projects/{pid}/requirements", data={"statement": text}, headers=H)
    page = ctx.new_page()
    page.goto(f"{BASE}/#/p/{pid}/requirements")
    page.wait_for_selector("tr.clickable")
    page.get_by_label("Select REQ-001").check()
    page.get_by_label("Select REQ-002").check()
    page.get_by_role("button", name="Tag…").click()
    page.wait_for_selector(".modal")
    page.get_by_label("Compliance tag").fill("SOX")
    page.locator(".modal-foot").get_by_role("button", name="Apply").click()
    page.wait_for_selector("text=2 requirements updated")
    page.reload()
    page.wait_for_selector("tr.clickable")
    page.get_by_label("Select REQ-001").check()
    page.get_by_role("button", name="Tag…").click()
    page.wait_for_selector(".modal")
    check(page.locator("datalist#known-tags option[value=SOX]").count() == 1, "tags already in use are offered as suggestions")
    page.keyboard.press("Escape")
    got = ctx.request.get(f"{BASE}/api/projects/{pid}/requirements").json()
    check(all(r["compliance_tags"] == ["SOX"] for r in got), "both requirements now carry the tag")
    ctx.request.post(f"{BASE}/api/projects/{pid}/requirements", data={"statement": "The system shall email receipts to buyers."}, headers=H)
    page.reload()
    page.wait_for_selector("tr.clickable")
    check(page.locator("tr.clickable").count() == 3, "three requirements before filtering")
    page.get_by_label("Compliance tag").select_option("SOX")
    page.wait_for_function("document.querySelectorAll('tr.clickable').length === 2")
    check(True, "filtering by the tag leaves the two that carry it")
    for title in ("Export invoices", "Email receipts"):
        ctx.request.post(f"{BASE}/api/projects/{pid}/stories", data={"title": title}, headers=H)
    page.goto(f"{BASE}/#/p/{pid}/stories")
    page.wait_for_selector("text=Export invoices")
    page.get_by_role("button", name="List").click()
    boxes = page.locator("tbody input[type=checkbox]")
    boxes.nth(0).check()
    boxes.nth(1).check()
    page.get_by_role("button", name="Tag…").click()
    page.wait_for_selector(".modal")
    page.get_by_label("Compliance tag").fill("GDPR")
    page.locator(".modal-foot").get_by_role("button", name="Apply").click()
    page.wait_for_selector("text=2 stories updated")
    stories = ctx.request.get(f"{BASE}/api/projects/{pid}/stories").json()
    check(all(s["compliance_tags"] == ["GDPR"] for s in stories), "both stories now carry the tag")
    ctx.request.post(f"{BASE}/api/projects/{pid}/stories", data={"title": "Archive old orders"}, headers=H)
    page.reload()
    page.get_by_role("button", name="List").click()
    page.wait_for_selector("tr.clickable")
    check(page.locator("tr.clickable").count() == 3, "three stories before filtering")
    check(page.locator("tr", has_text="Export invoices").locator(".badge", has_text="GDPR").count() == 1, "the stories list shows a story's compliance tags")
    page.get_by_label("Compliance tag").select_option("GDPR")
    page.wait_for_function("document.querySelectorAll('tr.clickable').length === 2")
    check(True, "filtering stories by the tag leaves the two that carry it")
    page.goto(f"{BASE}/#/p/{pid}/overview")
    page.wait_for_selector("text=Compliance coverage")
    card = page.locator(".card", has=page.get_by_role("heading", name="Compliance coverage")).bounding_box()
    check(card["width"] > 900, "the compliance card spans the page instead of leaving a gap beside the requirement mix (%dpx)" % card["width"])
    check(page.locator("tr", has_text="SOX").locator("text=0 of 2").count() == 1, "the overview shows SOX on 2 requirements, none covered yet")
    page.get_by_role("button", name="Rename SOX").click()
    page.wait_for_selector(".modal")
    page.get_by_label("New name").fill("Sarbanes-Oxley")
    page.locator(".modal-foot").get_by_role("button", name="Rename", exact=True).click()
    page.wait_for_selector("tr:has-text('Sarbanes-Oxley')")
    check(page.locator("tr", has_text="SOX").count() == 0, "renaming the tag changes it in the coverage card")
    page.get_by_role("link", name="Sarbanes-Oxley").click()
    page.wait_for_function("document.querySelectorAll('tr.clickable').length === 2")
    check(page.get_by_label("Compliance tag").input_value() == "Sarbanes-Oxley", "the tag on the overview opens the requirements already filtered to it")
    page.goto(f"{BASE}/#/p/{pid}/trace")
    page.wait_for_selector("text=Download matrix")
    check(page.get_by_role("link", name="Compliance matrix").count() == 1, "the traceability page offers the compliance matrix once tags are in use")
    page.goto(f"{BASE}/#/p/{pid}/export")
    page.wait_for_selector("text=What to export")
    page.get_by_label("Compliance tag").select_option("Sarbanes-Oxley")
    page.wait_for_selector("text=Narrowed to the requirements tagged Sarbanes-Oxley")
    with page.expect_download() as asked:
        page.locator(".card", has=page.get_by_role("heading", name="JSON")).get_by_role("button", name="Download").click()
    check("tag=Sarbanes-Oxley" in asked.value.url, "the download asks for the chosen compliance tag (%s)" % asked.value.url[-60:])
    ctx.request.post(f"{BASE}/api/projects/{pid}/baselines", data={"name": "Audit freeze", "scope": "all"}, headers=H)
    page.reload()
    page.wait_for_selector("text=Audit freeze")
    page.get_by_label("Compliance tag").select_option("Sarbanes-Oxley")
    with page.expect_download() as asked:
        page.locator("tr, .row", has_text="Audit freeze").get_by_role("button", name="Export", exact=True).first.click()
    check("tag=Sarbanes-Oxley" in asked.value.url and "/baselines/" in asked.value.url, "a baseline's Export also asks for the chosen tag (%s)" % asked.value.url[-70:])
    browser.close()
sys.exit(1 if failures else 0)
